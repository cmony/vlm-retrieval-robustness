def main() -> None:
    parser = argparse.ArgumentParser(description="RoCOCO gallery-injection evaluation")
    parser.add_argument("--data_root", default="./rococo_run",
                        help="working directory for annotations, cache and results")
    parser.add_argument("--coco_val2014", default=None,
                        help="directory holding COCO val2014 JPEGs")
    parser.add_argument("--models", nargs="+", default=list(MODEL_CONFIGS),
                        choices=list(MODEL_CONFIGS))
    parser.add_argument("--perturbations", nargs="+", default=PERTURBATIONS,
                        choices=PERTURBATIONS)
    parser.add_argument("--image_attack", action="store_true",
                        help="also run the image-mixing attack (text-to-image)")
    parser.add_argument("--mix_method", default="mix", choices=["mix", "patch"])
    parser.add_argument("--lam", type=float, default=0.9)
    parser.add_argument("--seeds", nargs="+", type=int, default=[1],
                        help="mixing seeds; the paper averages 1 10 100")
    parser.add_argument("--natural_csv", default=None,
                        help="condition_aggregate.csv from the main experiment")
    parser.add_argument("--batch_size", type=int, default=64)
    parser.add_argument("--cache-only", action="store_true",
                        help="reuse existing NPY caches; do not load models or COCO images")
    parser.add_argument("--results-output-dir", default=None,
                        help="directory for JSON/CSV outputs")
    args = parser.parse_args()
    if not args.cache_only and not args.coco_val2014:
        parser.error("--coco_val2014 is required unless --cache-only is used")

    root = Path(args.data_root)
    ann_dir = root / "annotations"
    cache_dir = root / "cache"
    cache_dir.mkdir(parents=True, exist_ok=True)

    print(f"device: {DEVICE}")

    print("\n[1/4] annotations")
    download_annotations(ann_dir)
    data = load_annotations(ann_dir)

    print("\n[2/4] images")
    images = None
    mixed_by_seed = {}
    if args.cache_only:
        print("  cache-only mode: skipped COCO image loading and image mixing")
        if args.image_attack:
            mixed_by_seed = {seed: None for seed in args.seeds}
    else:
        image_dir = Path(args.coco_val2014)
        missing = [f for f in data["image_files"][:20]
                   if not (image_dir / Path(f).name).exists()]
        if missing:
            raise SystemExit(
                f"COCO val2014 images not found under {image_dir}.\n"
                f"  expected e.g. {image_dir / Path(data['image_files'][0]).name}\n"
                "  wget http://images.cocodataset.org/zips/val2014.zip")

        images = [Image.open(image_dir / Path(f).name).convert("RGB")
                  for f in data["image_files"]]
        print(f"  loaded {len(images):,} images")

        if args.image_attack:
            for seed in args.seeds:
                print(f"  mixing images ({args.mix_method}, lam={args.lam}, seed={seed})")
                mixed_by_seed[seed] = build_mixed_images(
                    images, args.mix_method, args.lam, seed, args.batch_size)

    print("\n[3/4] evaluation")
    results: dict[str, dict] = {}

    for model_name in args.models:
        print(f"\n  {MODEL_LABEL[model_name]}")
        model = processor = model_type = None
        if not args.cache_only:
            model, processor, model_type = load_model(model_name)
        results[model_name] = {"text_attack": {}, "image_attack": {}}

        img_cache = cache_dir / f"{model_name}_img.npy"
        if img_cache.exists():
            img_emb = np.load(img_cache)
        elif args.cache_only:
            raise FileNotFoundError(f"missing image embedding cache: {img_cache}")
        else:
            img_emb = encode_images(model, processor, images, model_type, args.batch_size)
            np.save(img_cache, img_emb)

        gt_cache = cache_dir / f"{model_name}_gt.npy"
        if gt_cache.exists():
            gt_emb = np.load(gt_cache)
        elif args.cache_only:
            raise FileNotFoundError(f"missing ground-truth caption cache: {gt_cache}")
        else:
            gt_emb = encode_texts(model, processor, data["gt_captions"], model_type)
            np.save(gt_cache, gt_emb)

        # ---- text attack
        for pert in args.perturbations:
            adv_cache = cache_dir / f"{model_name}_{pert}.npy"
            if adv_cache.exists():
                adv_emb = np.load(adv_cache)
            elif args.cache_only:
                raise FileNotFoundError(f"missing adversarial caption cache: {adv_cache}")
            else:
                adv_emb = encode_texts(model, processor,
                                       data["adversarial"][pert], model_type)
                np.save(adv_cache, adv_emb)

            res = evaluate_text_attack(img_emb, gt_emb, adv_emb,
                                       data["gt_owner"], data["n_images"])
            results[model_name]["text_attack"][pert] = res
            print(f"    {PERTURBATION_LABEL[pert]:14s} "
                  f"R@1 {res['clean']['r@1']:.4f} -> {res['attacked']['r@1']:.4f}  "
                  f"delta {res['delta_r1']:+.4f}  "
                  f"S2F {res['stf_r1']:.4f}  "
                  f"wrong-top1 {res['attacked']['wrong_top1_rate']:.4f}  "
                  f"injected-top1 {res['attacked']['injected_top1_rate']:.4f}")

        # ---- image attack
        if args.image_attack:
            per_seed = []
            for seed, mixed in mixed_by_seed.items():
                mix_cache = cache_dir / f"{model_name}_mix_{args.mix_method}_{args.lam}_{seed}.npy"
                if mix_cache.exists():
                    mixed_emb = np.load(mix_cache)
                elif args.cache_only:
                    raise FileNotFoundError(f"missing mixed-image cache: {mix_cache}")
                else:
                    mixed_emb = encode_images(model, processor, mixed,
                                              model_type, args.batch_size)
                    np.save(mix_cache, mixed_emb)

                per_seed.append(evaluate_image_attack(
                    img_emb, mixed_emb, gt_emb, data["gt_owner"]))

            averaged = {
                "delta_r1": float(np.mean([r["delta_r1"] for r in per_seed])),
                "delta_r5": float(np.mean([r["delta_r5"] for r in per_seed])),
                "delta_r10": float(np.mean([r["delta_r10"] for r in per_seed])),
                "stf_r1": float(np.mean([r["stf_r1"] for r in per_seed])),
                "clean_r1": float(np.mean([r["clean"]["r@1"] for r in per_seed])),
                "attacked_r1": float(np.mean([r["attacked"]["r@1"] for r in per_seed])),
                "wrong_top1_rate": float(np.mean(
                    [r["attacked"]["wrong_top1_rate"] for r in per_seed])),
                "injected_top1_rate": float(np.mean(
                    [r["attacked"]["injected_top1_rate"] for r in per_seed])),
                "clean_success_count_r1": int(per_seed[0]["clean_success_count_r1"]),
                "success_to_failure_count_r1": float(np.mean(
                    [r["success_to_failure_count_r1"] for r in per_seed])),
                "seeds": list(mixed_by_seed),
                "method": args.mix_method,
                "lam": args.lam,
            }
            results[model_name]["image_attack"] = averaged
            print(f"    {args.mix_method}-{args.lam:<10} "
                  f"R@1 {averaged['clean_r1']:.4f} -> {averaged['attacked_r1']:.4f}  "
                  f"delta {averaged['delta_r1']:+.4f}  "
                  f"S2F {averaged['stf_r1']:.4f}  "
                  f"wrong-top1 {averaged['wrong_top1_rate']:.4f}  "
                  f"injected-top1 {averaged['injected_top1_rate']:.4f}")

        del model, processor
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    print("\n[4/4] outputs")
    results_dir = (
        Path(args.results_output_dir).expanduser().resolve()
        if args.results_output_dir
        else root / "results"
    )
    results_dir.mkdir(parents=True, exist_ok=True)

    with open(results_dir / "rococo_results.json", "w") as fh:
        json.dump(results, fh, indent=2)
    print(f"  wrote {results_dir/'rococo_results.json'}")

    try:
        import pandas as pd

        rows = []
        for model_name, blocks in results.items():
            for pert, res in blocks["text_attack"].items():
                rows.append({
                    "model": model_name,
                    "attack": "text_injection",
                    "perturbation": pert,
                    "direction": "image_to_text",
                    "r1_clean": res["clean"]["r@1"],
                    "r1_attacked": res["attacked"]["r@1"],
                    "delta_r1": res["delta_r1"],
                    "delta_r5": res["delta_r5"],
                    "delta_r10": res["delta_r10"],
                    "stf_r1": res["stf_r1"],
                    "clean_success_count_r1": res["clean_success_count_r1"],
                    "success_to_failure_count_r1": res["success_to_failure_count_r1"],
                    "wrong_top1_rate": res["attacked"]["wrong_top1_rate"],
                    "injected_top1_rate": res["attacked"]["injected_top1_rate"],
                    "gallery_clean": res["gallery_clean"],
                    "gallery_attacked": res["gallery_attacked"],
                })
            if blocks["image_attack"]:
                block = blocks["image_attack"]
                rows.append({
                    "model": model_name,
                    "attack": "image_mixing",
                    "perturbation": f"{block['method']}_{block['lam']}",
                    "direction": "text_to_image",
                    "r1_clean": block["clean_r1"],
                    "r1_attacked": block["attacked_r1"],
                    "delta_r1": block["delta_r1"],
                    "delta_r5": block["delta_r5"],
                    "delta_r10": block["delta_r10"],
                    "stf_r1": block["stf_r1"],
                    "clean_success_count_r1": block["clean_success_count_r1"],
                    "success_to_failure_count_r1": block["success_to_failure_count_r1"],
                    "wrong_top1_rate": block["wrong_top1_rate"],
                    "injected_top1_rate": block["injected_top1_rate"],
                    "gallery_clean": None,
                    "gallery_attacked": None,
                })

        pd.DataFrame(rows).to_csv(results_dir / "rococo_results.csv", index=False)
        print(f"  wrote {results_dir/'rococo_results.csv'}")
    except ImportError:
        print("  pandas unavailable, skipped CSV export")

    plot_comparison(results, args.natural_csv, root / "figures")

    print("\nsummary: delta R@1, image-to-text caption injection")
    header = f"  {'model':<16}" + "".join(f"{PERTURBATION_LABEL[p]:>15}" for p in args.perturbations)
    print(header)
    print("  " + "-" * (len(header) - 2))
    for model_name in args.models:
        line = f"  {MODEL_LABEL[model_name]:<16}"
        for pert in args.perturbations:
            line += f"{results[model_name]['text_attack'][pert]['delta_r1']:>+15.4f}"
        print(line)


if __name__ == "__main__":
    main()
