def load_model(name: str):
    from transformers import (
        BlipForImageTextRetrieval,
        BlipProcessor,
        CLIPModel,
        CLIPProcessor,
        SiglipModel,
        SiglipProcessor,
    )

    cfg = MODEL_CONFIGS[name]
    if cfg["type"] == "clip":
        model = CLIPModel.from_pretrained(cfg["hf"])
        processor = CLIPProcessor.from_pretrained(cfg["hf"])
    elif cfg["type"] == "siglip":
        model = SiglipModel.from_pretrained(cfg["hf"])
        processor = SiglipProcessor.from_pretrained(cfg["hf"])
    else:
        model = BlipForImageTextRetrieval.from_pretrained(cfg["hf"])
        processor = BlipProcessor.from_pretrained(cfg["hf"])

    return model.to(DEVICE).eval(), processor, cfg["type"]


@torch.no_grad()
def encode_images(model, processor, images, model_type: str, batch_size: int = 64) -> np.ndarray:
    out = []
    for i in range(0, len(images), batch_size):
        batch = images[i:i + batch_size]
        inputs = processor(images=batch, return_tensors="pt").to(DEVICE)
        if model_type == "clip":
            emb = model.get_image_features(**inputs)
        elif model_type == "siglip":
            emb = model.get_image_features(pixel_values=inputs["pixel_values"])
        else:
            vision = model.vision_model(pixel_values=inputs["pixel_values"])
            emb = model.vision_proj(vision.last_hidden_state[:, 0, :])
        out.append(F.normalize(emb.float(), dim=-1).cpu().numpy())
    return np.concatenate(out, axis=0)


@torch.no_grad()
def encode_texts(model, processor, texts, model_type: str, batch_size: int = 256) -> np.ndarray:
    out = []
    for i in range(0, len(texts), batch_size):
        batch = texts[i:i + batch_size]
        if model_type == "siglip":
            # SigLIP was trained with a fixed 64-token padded context.
            inputs = processor(text=batch, return_tensors="pt",
                               padding="max_length", max_length=64,
                               truncation=True).to(DEVICE)
            emb = model.get_text_features(input_ids=inputs["input_ids"])
        elif model_type == "clip":
            inputs = processor(text=batch, return_tensors="pt", padding=True,
                               truncation=True, max_length=77).to(DEVICE)
            emb = model.get_text_features(**inputs)
        else:
            inputs = processor(text=batch, return_tensors="pt", padding=True,
                               truncation=True, max_length=64).to(DEVICE)
            text_out = model.text_encoder(input_ids=inputs["input_ids"],
                                          attention_mask=inputs["attention_mask"])
            emb = model.text_proj(text_out.last_hidden_state[:, 0, :])
        out.append(F.normalize(emb.float(), dim=-1).cpu().numpy())
    return np.concatenate(out, axis=0)


# --------------------------------------------------------------------------
# Ranking
# --------------------------------------------------------------------------

def _best_rank_and_top1(sims: np.ndarray, gt_mask_fn, chunk: int = 256):
    """Rank of the best ground-truth item, and whether top-1 is ground truth.

    Ranks are 1-based. Chunked over queries so a 25,010 x 50,010 similarity
    matrix is never materialised in full. The implementation avoids sorting
    the whole gallery: the best ground-truth rank is one plus the number of
    gallery scores strictly above the best ground-truth score.
    """
    n_query = sims.shape[0]
    best_rank = np.zeros(n_query, dtype=np.int64)
    top1_is_gt = np.zeros(n_query, dtype=bool)
    top1_index = np.zeros(n_query, dtype=np.int64)

    for start in range(0, n_query, chunk):
        stop = min(start + chunk, n_query)
        block = sims[start:stop]

        for local, q in enumerate(range(start, stop)):
            gt = gt_mask_fn(q)
            row = block[local]
            top = int(np.argmax(row))
            best_gt_score = float(np.max(row[gt]))
            best_rank[q] = int(np.count_nonzero(row > best_gt_score) + 1)
            top1_is_gt[q] = bool(np.isin(top, gt))
            top1_index[q] = top

    return best_rank, top1_is_gt, top1_index


# --------------------------------------------------------------------------
# Image attack (verbatim port of the authors' mix_images.py)
# --------------------------------------------------------------------------

def rand_bbox(width: int, height: int, lam: float):
    cut_rat = np.sqrt(1.0 - lam)
    cut_w, cut_h = int(width * cut_rat), int(height * cut_rat)
    cx, cy = np.random.randint(width), np.random.randint(height)
    return (
        np.clip(cx - cut_w // 2, 0, width),
        np.clip(cy - cut_h // 2, 0, height),
        np.clip(cx + cut_w // 2, 0, width),
        np.clip(cy + cut_h // 2, 0, height),
    )


def build_mixed_images(images, method: str, lam: float, seed: int, batch_size: int = 64):
    """Replicate mix_images.py: 384x384 bicubic, shuffled batches, in-batch mixing.

    The upstream script shuffles the DataLoader, so a mixing partner is drawn
    from within the same batch and the partner assignment depends on the seed.
    Kept in memory rather than written to disk.
    """
    import torchvision.transforms as transforms
    from torchvision.transforms.functional import InterpolationMode

    torch.manual_seed(seed)
    np.random.seed(seed)

    to_tensor = transforms.Compose([
        transforms.Resize((384, 384), interpolation=InterpolationMode.BICUBIC),
        transforms.ToTensor(),
    ])

    generator = torch.Generator().manual_seed(seed)
    shuffled = torch.randperm(len(images), generator=generator).tolist()

    mixed = [None] * len(images)
    for start in range(0, len(shuffled), batch_size):
        idx = shuffled[start:start + batch_size]
        batch = torch.stack([to_tensor(images[i]) for i in idx])

        partner = torch.randperm(batch.size(0), generator=generator)
        if method == "patch":
            x1, y1, x2, y2 = rand_bbox(batch.size(2), batch.size(3), lam)
            batch[:, :, x1:x2, y1:y2] = batch[partner, :, x1:x2, y1:y2]
        else:
            batch = lam * batch + (1.0 - lam) * batch[partner, :]

        arr = (batch.clamp(0, 1) * 255).round().byte().permute(0, 2, 3, 1).numpy()
        for local, i in enumerate(idx):
            mixed[i] = Image.fromarray(arr[local])

    return mixed


