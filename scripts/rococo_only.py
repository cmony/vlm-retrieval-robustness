# Evaluation
# --------------------------------------------------------------------------

def evaluate_text_attack(img_emb, gt_emb, adv_emb, gt_owner, n_images) -> dict:
    """Image-to-text with adversarial captions injected into the gallery."""
    owner_index = [np.where(gt_owner == i)[0] for i in range(n_images)]

    sims_clean = img_emb @ gt_emb.T
    clean_rank, clean_top1, clean_top1_index = _best_rank_and_top1(
        sims_clean, lambda q: owner_index[q])

    sims_attacked = img_emb @ np.concatenate([gt_emb, adv_emb], axis=0).T
    att_rank, att_top1, att_top1_index = _best_rank_and_top1(
        sims_attacked, lambda q: owner_index[q])

    clean = retrieval_stats(clean_rank, clean_top1, clean_top1_index)
    attacked = retrieval_stats(att_rank, att_top1, att_top1_index, gt_emb.shape[0])
    transition = success_to_failure(clean_rank, att_rank, k=1)
    return {
        "clean": clean,
        "attacked": attacked,
        "delta_r1": attacked["r@1"] - clean["r@1"],
        "delta_r5": attacked["r@5"] - clean["r@5"],
        "delta_r10": attacked["r@10"] - clean["r@10"],
        "stf_r1": transition["success_to_failure_rate"],
        "clean_success_count_r1": transition["clean_success_count"],
        "success_to_failure_count_r1": transition["success_to_failure_count"],
        "gallery_clean": int(gt_emb.shape[0]),
        "gallery_attacked": int(gt_emb.shape[0] + adv_emb.shape[0]),
    }


def evaluate_image_attack(img_emb, mixed_emb, gt_emb, gt_owner) -> dict:
    """Text-to-image with mixed images injected into the gallery."""
    sims_clean = gt_emb @ img_emb.T
    clean_rank, clean_top1, clean_top1_index = _best_rank_and_top1(
        sims_clean, lambda q: np.array([gt_owner[q]]))

    sims_attacked = gt_emb @ np.concatenate([img_emb, mixed_emb], axis=0).T
    att_rank, att_top1, att_top1_index = _best_rank_and_top1(
        sims_attacked, lambda q: np.array([gt_owner[q]]))

    clean = retrieval_stats(clean_rank, clean_top1, clean_top1_index)
    attacked = retrieval_stats(att_rank, att_top1, att_top1_index, img_emb.shape[0])
    transition = success_to_failure(clean_rank, att_rank, k=1)
    return {
        "clean": clean,
        "attacked": attacked,
        "delta_r1": attacked["r@1"] - clean["r@1"],
        "delta_r5": attacked["r@5"] - clean["r@5"],
        "delta_r10": attacked["r@10"] - clean["r@10"],
        "stf_r1": transition["success_to_failure_rate"],
        "clean_success_count_r1": transition["clean_success_count"],
        "success_to_failure_count_r1": transition["success_to_failure_count"],
        "gallery_clean": int(img_emb.shape[0]),
        "gallery_attacked": int(img_emb.shape[0] + mixed_emb.shape[0]),
    }


