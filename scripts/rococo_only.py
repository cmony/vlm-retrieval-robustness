def download_annotations(ann_dir: Path) -> None:
    """Fetch the four perturbation files plus the clean Karpathy list."""
    ann_dir.mkdir(parents=True, exist_ok=True)
    for name in PERTURBATIONS + ["coco_karpathy_test"]:
        dst = ann_dir / f"{name}.json"
        if dst.exists():
            continue
        url = ROCOCO_RAW + f"{name}.json"
        print(f"  downloading {name}.json")
        urllib.request.urlretrieve(url, dst)


def parse_image_id(path: str) -> int:
    """'val2014/COCO_val2014_000000391895.jpg' -> 391895."""
    match = re.search(r"_(\d+)\.jpg$", path)
    if match is None:
        raise ValueError(f"cannot parse image id from {path!r}")
    return int(match.group(1))


def load_annotations(ann_dir: Path) -> dict:
    """Split each record into ground-truth and adversarial captions.

    The ground-truth block is identified by length from the clean Karpathy
    file rather than assumed to be 5, because 10 of the 5,000 images carry 6
    reference captions. Alignment is asserted, not trusted.
    """
    karpathy = json.load(open(ann_dir / "coco_karpathy_test.json"))
    n_images = len(karpathy)

    image_files = [rec["image"] for rec in karpathy]
    image_ids = [parse_image_id(p) for p in image_files]
    n_gt_per_image = [len(rec["caption"]) for rec in karpathy]

    gt_captions: list[str] = []
    gt_owner: list[int] = []           # gt_captions[j] belongs to image gt_owner[j]
    for img_idx, rec in enumerate(karpathy):
        for cap in rec["caption"]:
            gt_captions.append(cap)
            gt_owner.append(img_idx)

    adversarial: dict[str, list[str]] = {}
    for pert in PERTURBATIONS:
        records = json.load(open(ann_dir / f"{pert}.json"))
        if len(records) != n_images:
            raise ValueError(f"{pert}: expected {n_images} records, got {len(records)}")

        caps: list[str] = []
        for img_idx, rec in enumerate(records):
            if rec["image"] != image_files[img_idx]:
                raise ValueError(f"{pert}: record {img_idx} is not aligned with Karpathy list")

            n_gt = n_gt_per_image[img_idx]
            if rec["caption"][:n_gt] != karpathy[img_idx]["caption"]:
                raise ValueError(f"{pert}: ground-truth block mismatch at record {img_idx}")

            adv = rec["caption"][n_gt:]
            if len(adv) != 5:
                raise ValueError(f"{pert}: record {img_idx} has {len(adv)} adversarial captions, expected 5")
            caps.extend(adv)

        adversarial[pert] = caps
        print(f"  {pert:14s} {len(caps):,} adversarial captions")

    print(f"  ground truth   {len(gt_captions):,} captions over {n_images:,} images")

    return {
        "n_images": n_images,
        "image_files": image_files,
        "image_ids": image_ids,
        "gt_captions": gt_captions,
        "gt_owner": np.asarray(gt_owner, dtype=np.int64),
        "adversarial": adversarial,
    }


