def plot_comparison(results: dict, natural_csv: Path | None, out_dir: Path) -> None:
    """Left: delta R@1 per perturbation. Right: worst natural vs worst RoCOCO.

    Only deltas are plotted. Absolute R@1 is not comparable across the two
    experiments because they use different image splits.
    """
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.patches as mpatches
    import matplotlib.pyplot as plt

    plt.rcParams.update({
        "font.family": "serif",
        "font.serif": ["Liberation Serif", "DejaVu Serif"],
        "font.size": 8,
        "axes.labelsize": 8,
        "axes.titlesize": 8.5,
        "xtick.labelsize": 7.5,
        "ytick.labelsize": 7.5,
        "legend.fontsize": 7,
        "axes.linewidth": 0.6,
        "savefig.dpi": 300,
        "figure.dpi": 300,
    })

    models = [m for m in MODEL_CONFIGS if m in results]
    have_natural = natural_csv is not None and Path(natural_csv).exists()
    n_panels = 2 if have_natural else 1

    fig, axes = plt.subplots(1, n_panels, figsize=(7.16 if have_natural else 3.6, 2.8))
    if n_panels == 1:
        axes = [axes]

    # ---- panel 1: text attack per perturbation
    ax = axes[0]
    x = np.arange(len(PERTURBATIONS))
    width = 0.8 / max(len(models), 1)

    for i, model in enumerate(models):
        values = [results[model]["text_attack"].get(p, {}).get("delta_r1", np.nan)
                  for p in PERTURBATIONS]
        ax.bar(x + (i - (len(models) - 1) / 2) * width, values, width=width,
               color=MODEL_COLOR[model], label=MODEL_LABEL[model], zorder=3)

    ax.axhline(0, color="0.25", lw=0.7, zorder=2)
    ax.set_xticks(x)
    ax.set_xticklabels([PERTURBATION_LABEL[p] for p in PERTURBATIONS],
                       rotation=15, ha="right")
    ax.set_ylabel(r"$\Delta$R@1 (image-to-text)")
    ax.set_title("RoCOCO caption injection", pad=4)
    ax.grid(axis="y", color="0.88", zorder=0)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    ax.legend(loc="lower left", framealpha=0.95, edgecolor="0.8", handlelength=1.4)

    # ---- panel 2: worst natural distortion vs worst RoCOCO
    if have_natural:
        import pandas as pd

        agg = pd.read_csv(natural_csv, low_memory=False)
        clean_r1 = agg[agg["family"] == "clean"].set_index(["model", "direction"])["r1"]
        distorted = agg[agg["family"] != "clean"].copy()
        distorted["delta_r1"] = [
            row.r1 - clean_r1[(row.model, row.direction)]
            for row in distorted.itertuples()
        ]
        i2t = distorted[distorted["direction"] == "image_to_text"]
        worst_natural = i2t.groupby("model")["delta_r1"].min()

        ax2 = axes[1]
        x2 = np.arange(len(models))
        natural_vals = [worst_natural.get(m, np.nan) for m in models]
        rococo_vals = [
            min(results[m]["text_attack"][p]["delta_r1"]
                for p in results[m]["text_attack"])
            for m in models
        ]

        ax2.bar(x2 - 0.19, natural_vals, width=0.36,
                color=[MODEL_COLOR[m] for m in models], zorder=3)
        ax2.bar(x2 + 0.19, rococo_vals, width=0.36,
                color=[MODEL_COLOR[m] for m in models], alpha=0.45,
                hatch="///", edgecolor="white", linewidth=0.4, zorder=3)

        ax2.axhline(0, color="0.25", lw=0.7, zorder=2)
        ax2.set_xticks(x2)
        ax2.set_xticklabels([MODEL_LABEL[m] for m in models], rotation=15, ha="right")
        ax2.set_ylabel(r"Worst $\Delta$R@1 (image-to-text)")
        ax2.set_title("Query corruption vs. gallery poisoning", pad=4)
        ax2.grid(axis="y", color="0.88", zorder=0)
        ax2.set_axisbelow(True)
        for side in ("top", "right"):
            ax2.spines[side].set_visible(False)
        ax2.legend(
            handles=[
                mpatches.Patch(facecolor="0.45", label="Natural distortion (worst)"),
                mpatches.Patch(facecolor="0.45", alpha=0.45, hatch="///",
                               edgecolor="white", label="RoCOCO injection (worst)"),
            ],
            loc="lower left", framealpha=0.95, edgecolor="0.8")

    fig.tight_layout(pad=0.4, w_pad=1.0)
    out_dir.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(out_dir / f"fig5_rococo_comparison.{ext}",
                    dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"  wrote {out_dir/'fig5_rococo_comparison.pdf'}")


