#!/usr/bin/env python3
"""
RoCOCO Gallery-Injection Evaluation (standalone)
================================================
Companion experiment for the IEEE Access paper
  "Bidirectional Retrieval Robustness of Four Vision-Language Checkpoints
   Under Natural Distortions and Gallery-Contamination Stress Tests"

This script runs ONLY the RoCOCO comparison. It does not re-run the
34-condition natural-distortion experiment; it reads that experiment's
aggregate CSV to build the comparison figure.

--------------------------------------------------------------------------
WHAT RoCOCO IS (Park et al., ECCV 2024 Workshop; arXiv:2304.10727)
--------------------------------------------------------------------------
RoCOCO inserts adversarial items into the *gallery* (search pool) and asks
whether the model still ranks the true item first.

  Text attack  -> image-to-text. For each image, 5 adversarial captions are
                  generated by replacing ONE word in each ground-truth
                  caption. All 25,000 adversarial captions are added to the
                  caption gallery, which grows 25,010 -> 50,010.
                  Four generators, increasing semantic distance:
                    same_concept  same category  ("man"    -> "catchers")
                    diff_concept  other category ("man"    -> "dog")
                    rand_voca     random vocab   ("man"    -> "eyes")
  danger        semantically harmful or incompatible replacement

  Image attack -> text-to-image. Each image is blended with another image
                  from the same batch; the 5,000 altered images are added to
                  the image gallery, which grows 5,000 -> 10,000.
                    mix    : lam*img + (1-lam)*other          (alpha blend)
                    patch  : CutMix-style rectangular paste
                  The blend and bbox formulas are taken verbatim from the
                  authors' mix_images.py. Batches are drawn with an explicit
                  seeded generator instead of a multi-worker DataLoader, so
                  which image is paired with which differs from the authors'
                  own run even at the same seed; the procedure and its
                  statistics are unchanged. Averaging over seeds 1/10/100, as
                  the paper does, is what makes the number stable.

This is orthogonal to the main paper: natural distortion corrupts the
*query*, RoCOCO poisons the *gallery*.

--------------------------------------------------------------------------
VERIFIED DATA FACTS (checked against the released files, not assumed)
--------------------------------------------------------------------------
  * Each JSON is a list of 5,000 records, index-aligned with
    coco_karpathy_test.json.
  * Record = {"image": "val2014/COCO_val2014_*.jpg", "caption": [...]}.
  * caption[:n_gt] are the ground-truth captions and match
    coco_karpathy_test.json EXACTLY for all 5,000 records.
    n_gt is 5 for 4,990 images and 6 for 10 images -- do NOT hardcode 5.
  * caption[n_gt:] are always exactly 5 adversarial captions.
  * Totals: 25,010 ground-truth captions, 25,000 adversarial captions.

  !! IMAGE SET WARNING !!
  RoCOCO uses the Karpathy test split, which lives in COCO **val2014**.
  It is NOT the COCO val2017 set used by the main experiment: the two share
  only 593 of 5,000 images (11.9%). val2014 must be downloaded separately,
  and clean baselines therefore differ between the two experiments. For that
  reason the comparison figure plots ONLY delta R@1, never absolute R@1.

--------------------------------------------------------------------------
SCORING
--------------------------------------------------------------------------
All four models are scored by cosine similarity between L2-normalised
embeddings, identical to the main experiment. For BLIP this means the ITC
projections (vision_proj / text_proj), not the ITM head: ITM needs one
forward pass per pair, i.e. 5,000 x 50,010 passes, which is intractable.
The authors' own BLIP script reranks an ITC shortlist with ITM; we skip the
rerank so that the four models stay directly comparable.

Reported per model x perturbation:
  R@1/R@5/R@10 clean and attacked, and delta
  success-to-failure rate   fraction of queries correct at R@1 on the clean
                            gallery and wrong after injection
  wrong-top-1               unconditional fraction of queries whose attacked
                            top-1 result is not a clean ground-truth item
  injected-top-1            fraction of queries whose top-1 result is an
                            injected gallery item

--------------------------------------------------------------------------
USAGE
--------------------------------------------------------------------------
  # text attack only (default; no val2014 images needed for a dry run of
  # annotation parsing, but image encoding does need them)
  python rococo_only.py --data_root /content --coco_val2014 /content/val2014

  # add the image attack, paper settings (3 seeds averaged)
  python rococo_only.py --data_root /content --coco_val2014 /content/val2014 \
      --image_attack --mix_method mix --lam 0.9 --seeds 1 10 100

  # comparison figure against the natural-distortion run
  python rococo_only.py ... --natural_csv condition_aggregate.csv

Runtime, all 4 models: text attack ~25 min on A100 / ~70 min on T4.
Each additional image-attack seed adds ~5 min on A100 / ~15 min on T4.

Colab setup:
  !pip install -q transformers==4.40.0 accelerate sentencepiece
  !wget -q http://images.cocodataset.org/zips/val2014.zip -O /tmp/val2014.zip
  !unzip -q /tmp/val2014.zip -d /content/
"""

